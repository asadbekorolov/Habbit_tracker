-- ============================================================================
-- IDROK — public sxemaning to'liq DDL'ini jonli bazadan chiqarish
-- ============================================================================
-- Faqat o'qiydi: hech narsa yaratmaydi va o'zgartirmaydi.
-- Natija: bitta qator, bitta ustun (ddl) — 000_baseline_schema.sql mazmuni.
--
-- Ishga tushirish (ikkisidan biri):
--   1) node scripts/dump-baseline.mjs   (SUPABASE_DB_URL env bilan — faylni o'zi yozadi)
--   2) Supabase SQL Editor -> Run -> natija katagini nusxalab
--      supabase/baseline/000_baseline_schema.sql ga saqlang
--
-- Tartib: kengaytmalar, turlar, ketma-ketliklar, jadval turiga bog'liq bo'lmagan
-- funksiyalar, jadvallar, PK/UNIQUE/CHECK, jadval turiga bog'liq funksiyalar,
-- view'lar, FK, indekslar, triggerlar, RLS, policy'lar, huquqlar, realtime.
-- ============================================================================

WITH
ns AS (SELECT oid FROM pg_namespace WHERE nspname = 'public'),
tbl AS (
  SELECT c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relacl
  FROM pg_class c
  WHERE c.relnamespace = (SELECT oid FROM ns) AND c.relkind IN ('r', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e')
),
grantees AS (
  SELECT 0::oid AS oid, 'PUBLIC' AS name
  UNION ALL
  SELECT oid, quote_ident(rolname) FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role')
),
fn AS (
  SELECT p.oid, p.proname, p.proacl,
         pg_get_function_identity_arguments(p.oid) AS args,
         -- Qaytish yoki argument turi public jadval turi bo'lsa — jadvallardan keyin
         EXISTS (
           SELECT 1 FROM pg_type t
           WHERE t.oid = ANY (array_append(p.proargtypes::oid[], p.prorettype))
             AND t.typrelid <> 0 AND t.typnamespace = (SELECT oid FROM ns)
         ) AS needs_tables
  FROM pg_proc p
  WHERE p.pronamespace = (SELECT oid FROM ns) AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
),
-- k ::text — aks holda UNION uni `name` turiga (63 belgi) qisqartiradi.
stmts (sec, k, stmt) AS (
  -- 00. Sarlavha
  SELECT 0, ''::text, E'-- IDROK baseline sxema (public). Jonli bazadan generate_baseline.sql bilan olingan.\n'
             || '-- Sana: ' || to_char(now() AT TIME ZONE 'Asia/Tashkent', 'YYYY-MM-DD HH24:MI') || E' (Toshkent)\n'
             || E'SET check_function_bodies = false;\nSET client_min_messages = warning;'

  -- 01. Kengaytmalar
  UNION ALL
  SELECT 1, e.extname, format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname)
  FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname <> 'plpgsql'

  -- 02. Enum turlar
  UNION ALL
  SELECT 2, t.typname, format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
         (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid = t.oid))
  FROM pg_type t WHERE t.typnamespace = (SELECT oid FROM ns) AND t.typtype = 'e'

  -- 03. Mustaqil ketma-ketliklar (identity'ga tegishli bo'lmagan)
  UNION ALL
  SELECT 3, c.relname, format('CREATE SEQUENCE IF NOT EXISTS public.%I;', c.relname)
  FROM pg_class c
  WHERE c.relnamespace = (SELECT oid FROM ns) AND c.relkind = 'S'
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')

  -- 04. Funksiyalar (jadval turiga bog'liq emas)
  UNION ALL
  SELECT 4, fn.proname || '(' || fn.args || ')', pg_get_functiondef(fn.oid) || ';'
  FROM fn WHERE NOT fn.needs_tables

  -- 05. Jadvallar
  UNION ALL
  SELECT 5, t.relname, format(E'CREATE TABLE public.%I (\n%s\n);', t.relname, (
    SELECT string_agg(
      '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
              WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) ELSE '' END
      || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
      || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
      E',\n' ORDER BY a.attnum)
    FROM pg_attribute a
    LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped))
  FROM tbl t

  -- 06. PK / UNIQUE / CHECK / EXCLUDE
  UNION ALL
  SELECT 6, t.relname || '.' || con.conname,
         format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', t.relname, con.conname, pg_get_constraintdef(con.oid))
  FROM pg_constraint con JOIN tbl t ON t.oid = con.conrelid
  WHERE con.contype IN ('p', 'u', 'c', 'x')

  -- 07. Funksiyalar (jadval turiga bog'liq)
  UNION ALL
  SELECT 7, fn.proname || '(' || fn.args || ')', pg_get_functiondef(fn.oid) || ';'
  FROM fn WHERE fn.needs_tables

  -- 08. View'lar
  UNION ALL
  SELECT 8, lpad(c.oid::text, 12, '0'), format(E'CREATE OR REPLACE VIEW public.%I AS\n%s', c.relname, pg_get_viewdef(c.oid, true))
  FROM pg_class c WHERE c.relnamespace = (SELECT oid FROM ns) AND c.relkind = 'v'

  -- 09. Tashqi kalitlar
  UNION ALL
  SELECT 9, t.relname || '.' || con.conname,
         format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', t.relname, con.conname, pg_get_constraintdef(con.oid))
  FROM pg_constraint con JOIN tbl t ON t.oid = con.conrelid
  WHERE con.contype = 'f'

  -- 10. Indekslar (cheklovlarga tegishli bo'lmaganlari)
  UNION ALL
  SELECT 10, i.relname, pg_get_indexdef(ix.indexrelid) || ';'
  FROM pg_index ix JOIN pg_class i ON i.oid = ix.indexrelid JOIN tbl t ON t.oid = ix.indrelid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = ix.indexrelid)

  -- 11. Triggerlar
  UNION ALL
  SELECT 11, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid, true) || ';'
  FROM pg_trigger tg JOIN tbl t ON t.oid = tg.tgrelid
  WHERE NOT tg.tgisinternal

  -- 12. RLS
  UNION ALL
  SELECT 12, t.relname, format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
  FROM tbl t WHERE t.relrowsecurity
  UNION ALL
  SELECT 12, t.relname || '~force', format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', t.relname)
  FROM tbl t WHERE t.relforcerowsecurity

  -- 13. Policy'lar
  UNION ALL
  SELECT 13, t.relname || '.' || pol.polname,
         format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;',
           pol.polname, t.relname,
           CASE WHEN pol.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
           CASE pol.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
           CASE WHEN pol.polroles = '{0}'::oid[] THEN 'public'
                ELSE (SELECT string_agg(quote_ident(r.rolname), ', ' ORDER BY r.rolname) FROM pg_roles r WHERE r.oid = ANY (pol.polroles)) END,
           CASE WHEN pol.polqual IS NOT NULL THEN ' USING (' || pg_get_expr(pol.polqual, pol.polrelid) || ')' ELSE '' END,
           CASE WHEN pol.polwithcheck IS NOT NULL THEN ' WITH CHECK (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')' ELSE '' END)
  FROM pg_policy pol JOIN tbl t ON t.oid = pol.polrelid

  -- 14. Jadval huquqlari (anon / authenticated / service_role / PUBLIC)
  UNION ALL
  SELECT 14, t.relname || '#0', format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated, service_role;', t.relname)
  FROM tbl t
  UNION ALL
  SELECT 14, t.relname || '#1' || g.name, format('GRANT %s ON TABLE public.%I TO %s;',
         string_agg(DISTINCT x.privilege_type, ', ' ORDER BY x.privilege_type), t.relname, g.name)
  FROM tbl t CROSS JOIN LATERAL aclexplode(COALESCE(t.relacl, acldefault('r', (SELECT relowner FROM pg_class WHERE oid = t.oid)))) x
  JOIN grantees g ON g.oid = x.grantee
  GROUP BY t.relname, g.name

  -- 15. Ustun huquqlari (masalan profiles: shaxsiy ustunlar yopiq)
  UNION ALL
  SELECT 15, t.relname || '.' || g.name || '.' || x.privilege_type,
         format('GRANT %s (%s) ON TABLE public.%I TO %s;', x.privilege_type,
                string_agg(quote_ident(a.attname), ', ' ORDER BY a.attnum), t.relname, g.name)
  FROM tbl t
  JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped AND a.attacl IS NOT NULL
  CROSS JOIN LATERAL aclexplode(a.attacl) x
  JOIN grantees g ON g.oid = x.grantee
  GROUP BY t.relname, g.name, x.privilege_type

  -- 16. Funksiya huquqlari
  UNION ALL
  SELECT 16, fn.proname || '(' || fn.args || ')#0',
         format('REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC, anon, authenticated, service_role;', fn.proname, fn.args)
  FROM fn
  UNION ALL
  SELECT 16, fn.proname || '(' || fn.args || ')#1' || g.name,
         format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', fn.proname, fn.args, g.name)
  FROM fn CROSS JOIN LATERAL aclexplode(COALESCE(fn.proacl, acldefault('f', (SELECT proowner FROM pg_proc WHERE oid = fn.oid)))) x
  JOIN grantees g ON g.oid = x.grantee
  WHERE x.privilege_type = 'EXECUTE'

  -- 17. Realtime nashri
  UNION ALL
  SELECT 17, pt.tablename, format('ALTER PUBLICATION %I ADD TABLE public.%I;', pt.pubname, pt.tablename)
  FROM pg_publication_tables pt WHERE pt.schemaname = 'public'

  -- 18. Katalog ma'lumotlari (server narxlari — ularsiz do'kon/to'lov ishlamaydi)
  UNION ALL
  SELECT 18, 'coin_packs', 'INSERT INTO public.coin_packs SELECT * FROM json_populate_recordset(NULL::public.coin_packs, '
         || quote_literal(json_agg(c ORDER BY c.id)::text) || ') ON CONFLICT DO NOTHING;'
  FROM public.coin_packs c HAVING count(*) > 0
  UNION ALL
  SELECT 18, 'shop_items', 'INSERT INTO public.shop_items SELECT * FROM json_populate_recordset(NULL::public.shop_items, '
         || quote_literal(json_agg(s ORDER BY s.id)::text) || ') ON CONFLICT DO NOTHING;'
  FROM public.shop_items s HAVING count(*) > 0
)
-- COLLATE "C": bayt tartibi — natija har qanday baza tilida bir xil chiqadi.
SELECT string_agg(stmt, E'\n\n' ORDER BY sec, k COLLATE "C") || E'\n' AS ddl FROM stmts;
