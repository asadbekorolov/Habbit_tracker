-- ── To'lovni tasdiqlash: tanga qo'shish (bir marta) ──────────────────────────
CREATE OR REPLACE FUNCTION public.credit_payment(p_txn_id uuid)
RETURNS TABLE (status text, coins_added integer, new_balance integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  t payment_transactions%ROWTYPE;
  v_balance integer;
BEGIN
  SELECT * INTO t FROM payment_transactions WHERE id = p_txn_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'transaction_not_found';
  END IF;
  IF t.status = 'paid' THEN
    -- Takroriy callback: hech narsa qo'shilmaydi
    RETURN QUERY SELECT 'already_paid'::text, 0, (SELECT p.coins FROM profiles p WHERE p.id = t.user_id);
    RETURN;
  END IF;
  IF t.status IN ('cancelled', 'failed') THEN
    RAISE EXCEPTION 'transaction_cancelled';
  END IF;

  PERFORM _lock_user_rewards(t.user_id);
  PERFORM _apply_balance(t.user_id, 0, t.coins, 0);
  UPDATE payment_transactions
     SET status = 'paid', perform_time = now(), updated_at = now()
   WHERE id = t.id;

  SELECT p.coins INTO v_balance FROM profiles p WHERE p.id = t.user_id;
  RETURN QUERY SELECT 'paid'::text, t.coins, v_balance;
END;
$$;

-- ── Bekor qilish (to'langan bo'lsa tanga qaytarib olinadi, manfiy bo'lishi mumkin) ──
CREATE OR REPLACE FUNCTION public.cancel_payment(p_txn_id uuid, p_reason integer DEFAULT NULL)
RETURNS TABLE (status text, coins_removed integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  t payment_transactions%ROWTYPE;
  v_removed integer := 0;
BEGIN
  SELECT * INTO t FROM payment_transactions WHERE id = p_txn_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'transaction_not_found';
  END IF;
  IF t.status = 'cancelled' THEN
    RETURN QUERY SELECT 'already_cancelled'::text, 0;
    RETURN;
  END IF;

  IF t.status = 'paid' THEN
    PERFORM _lock_user_rewards(t.user_id);
    PERFORM _apply_balance(t.user_id, 0, -t.coins, 0);
    v_removed := t.coins;
  END IF;

  UPDATE payment_transactions
     SET status = 'cancelled', cancel_time = now(), cancel_reason = p_reason, updated_at = now()
   WHERE id = t.id;

  RETURN QUERY SELECT 'cancelled'::text, v_removed;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.credit_payment(uuid)          FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.cancel_payment(uuid, integer) FROM PUBLIC, anon, authenticated;
GRANT  EXECUTE ON FUNCTION public.credit_payment(uuid)          TO service_role;
GRANT  EXECUTE ON FUNCTION public.cancel_payment(uuid, integer) TO service_role;

