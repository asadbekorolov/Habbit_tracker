-- Avval mijoz o'zi to'lov havolasini yasardi (narx va user_id URL'da, server
-- hech narsani tekshirmasdi, tanga hech qachon tushmasdi). Endi:
--   coin_packs            — narxlar faqat serverda (mijoz faqat pack_id yuboradi)
--   payment_transactions  — har bir buyurtma; Click/Payme callback'lari shu
--                           qatorni holatdan holatga o'tkazadi
--   credit_payment(id)    — to'lov tasdiqlanganda tanga qo'shadi (idempotent)
--   cancel_payment(id, r) — bekor qilish; to'langan bo'lsa tangani qaytarib oladi
-- Yozish faqat service_role orqali (api/payments/*). Foydalanuvchi faqat o'z
-- tranzaksiyalarini o'qiy oladi. Qayta ishga tushirish xavfsiz.
-- ============================================================================

BEGIN;

