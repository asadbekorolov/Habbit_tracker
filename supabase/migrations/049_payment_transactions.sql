-- ── Tranzaksiyalar ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.payment_transactions (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Click merchant_prepare_id / merchant_confirm_id butun son bo'lishi kerak
  seq             bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id         uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  provider        text NOT NULL,
  pack_id         text NOT NULL REFERENCES public.coin_packs(id),
  amount_uzs      integer NOT NULL,
  coins           integer NOT NULL,                             -- coins + bonus (yaratilgan paytdagi)
  status          text NOT NULL DEFAULT 'created',
  provider_txn_id text,                                         -- click_trans_id / Payme transaction id
  provider_state  integer,                                      -- Payme: 1, 2, -1, -2
  provider_time   bigint,                                       -- Payme yaratish vaqti (ms)
  perform_time    timestamptz,
  cancel_time     timestamptz,
  cancel_reason   integer,
  last_payload    jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- Jonli bazada jadval eski sxema bilan oldindan mavjud bo'lishi mumkin
-- (masalan provider_trans_id ustuni bilan) — unda CREATE TABLE IF NOT EXISTS
