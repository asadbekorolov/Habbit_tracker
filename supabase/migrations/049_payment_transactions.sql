  ADD COLUMN IF NOT EXISTS seq             bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS user_id         uuid,
  ADD COLUMN IF NOT EXISTS provider        text,
  ADD COLUMN IF NOT EXISTS pack_id         text,
  ADD COLUMN IF NOT EXISTS amount_uzs      integer,
  ADD COLUMN IF NOT EXISTS coins           integer,
  ADD COLUMN IF NOT EXISTS status          text DEFAULT 'created',
  ADD COLUMN IF NOT EXISTS provider_txn_id text,
  ADD COLUMN IF NOT EXISTS provider_state  integer,
  ADD COLUMN IF NOT EXISTS provider_time   bigint,
  ADD COLUMN IF NOT EXISTS perform_time    timestamptz,
  ADD COLUMN IF NOT EXISTS cancel_time     timestamptz,
  ADD COLUMN IF NOT EXISTS cancel_reason   integer,
  ADD COLUMN IF NOT EXISTS last_payload    jsonb,
  ADD COLUMN IF NOT EXISTS created_at      timestamptz DEFAULT now(),
  ADD COLUMN IF NOT EXISTS updated_at      timestamptz DEFAULT now();

-- Eski jadvalni yangi sxemaga moslash. Yangi (bo'sh) bazada bu blok hech
-- narsani o'zgartirmaydi. Moslab bo'lmaydigan holat bo'lsa — aniq xabar bilan
-- to'xtaydi va BEGIN/COMMIT tufayli bazada hech narsa o'zgarmaydi.
DO $mig$
DECLARE
  tbl constant regclass := 'public.payment_transactions'::regclass;
  -- ustun => kutilgan tur
  want constant jsonb := '{
    "id": "uuid", "seq": "bigint", "user_id": "uuid", "provider": "text",
    "pack_id": "text", "amount_uzs": "integer", "coins": "integer", "status": "text",
    "provider_txn_id": "text", "provider_state": "integer", "provider_time": "bigint",
    "perform_time": "timestamp with time zone", "cancel_time": "timestamp with time zone",
    "cancel_reason": "integer", "last_payload": "jsonb",
    "created_at": "timestamp with time zone", "updated_at": "timestamp with time zone"
  }';
  ours    text[];
  r       record;
  col     text;
  bad     text[] := '{}';
  pk      text[];
  has_nul boolean;
BEGIN
  SELECT array_agg(k) INTO ours FROM jsonb_object_keys(want) k;

  -- 1) Bizning ustunlarga tegishli eski CHECK cheklovlari olib tashlanadi
  --    (masalan status IN ('pending','completed',...)); yangilari pastda qo'yiladi.
  FOR r IN
    SELECT c.conname FROM pg_constraint c
     WHERE c.conrelid = tbl AND c.contype = 'c'
       AND EXISTS (SELECT 1 FROM pg_attribute a
                    WHERE a.attrelid = tbl AND a.attnum = ANY (c.conkey) AND a.attname = ANY (ours))
  LOOP
    EXECUTE format('ALTER TABLE public.payment_transactions DROP CONSTRAINT %I', r.conname);
  END LOOP;

  -- 2) Ustun turi mos kelmasa — o'zgartirishga urinamiz (enum/varchar -> text va h.k.)
  FOR r IN
    SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS cur, want ->> a.attname AS exp,
           t.typcategory
      FROM pg_attribute a JOIN pg_type t ON t.oid = a.atttypid
     WHERE a.attrelid = tbl AND a.attnum > 0 AND NOT a.attisdropped AND a.attname = ANY (ours)
       AND format_type(a.atttypid, a.atttypmod) <> want ->> a.attname
  LOOP
    BEGIN
      EXECUTE format('ALTER TABLE public.payment_transactions ALTER COLUMN %I DROP DEFAULT', r.attname);
      IF r.exp = 'timestamp with time zone' AND r.typcategory = 'N' THEN
        -- raqam ko'rinishidagi vaqt (Payme uslubi, millisekund)
        EXECUTE format('ALTER TABLE public.payment_transactions ALTER COLUMN %I TYPE timestamptz USING to_timestamp(%I / 1000.0)',
                       r.attname, r.attname);
      ELSE
        EXECUTE format('ALTER TABLE public.payment_transactions ALTER COLUMN %I TYPE %s USING %I::text::%s',
                       r.attname, r.exp, r.attname, r.exp);
      END IF;
    EXCEPTION WHEN others THEN
      bad := bad || format('%s: %s -> %s (%s)', r.attname, r.cur, r.exp, SQLERRM);
    END;
  END LOOP;
  IF cardinality(bad) > 0 THEN
    RAISE EXCEPTION 'payment_transactions: ustun turlarini moslab bo''lmadi: %', array_to_string(bad, '; ')
      USING HINT = 'Hech narsa o''zgarmadi (tranzaksiya bekor qilindi). Shu xabarni dasturchiga yuboring.';
  END IF;

  -- 3) Eski ustundagi to'lov ID'si yangisiga ko'chiriladi
  FOREACH col IN ARRAY ARRAY['provider_trans_id', 'provider_transaction_id'] LOOP
    IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = tbl AND attname = col AND NOT attisdropped) THEN
      EXECUTE format('UPDATE public.payment_transactions SET provider_txn_id = %I::text
                       WHERE provider_txn_id IS NULL AND %I IS NOT NULL', col, col);
    END IF;
  END LOOP;

  -- 4) Eski holat nomlari yangisiga o'giriladi
  UPDATE public.payment_transactions SET status = CASE
           WHEN status IS NULL THEN 'created'
           WHEN lower(status) IN ('completed', 'complete', 'success', 'succeeded', 'paid') THEN 'paid'
           WHEN lower(status) IN ('canceled', 'cancelled') THEN 'cancelled'
           WHEN lower(status) IN ('created', 'pending', 'failed') THEN lower(status)
           ELSE 'failed' END
   WHERE status IS NULL OR status NOT IN ('created', 'pending', 'paid', 'cancelled', 'failed');
  UPDATE public.payment_transactions SET provider = lower(provider)
   WHERE provider IS NOT NULL AND provider <> lower(provider);
  UPDATE public.payment_transactions SET created_at = now() WHERE created_at IS NULL;
  UPDATE public.payment_transactions SET updated_at = now() WHERE updated_at IS NULL;
  UPDATE public.payment_transactions SET id = gen_random_uuid() WHERE id IS NULL;

  -- 5) Eski majburiy (NOT NULL) ustunlar yangi kodni to'sib qo'ymasin:
  --    create-invoice ularni to'ldirmaydi, shuning uchun ixtiyoriy qilinadi.
  FOR r IN
    SELECT a.attname FROM pg_attribute a
     WHERE a.attrelid = tbl AND a.attnum > 0 AND NOT a.attisdropped AND a.attnotnull
       AND a.attname <> ALL (ours)
       AND a.attidentity = '' AND NOT a.atthasdef
  LOOP
    EXECUTE format('ALTER TABLE public.payment_transactions ALTER COLUMN %I DROP NOT NULL', r.attname);
  END LOOP;

  -- 6) Asosiy kalit — id
  SELECT array_agg(a.attname::text ORDER BY a.attname) INTO pk
    FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
   WHERE c.conrelid = tbl AND c.contype = 'p';
  IF pk IS DISTINCT FROM ARRAY['id']::text[] THEN
    IF pk IS NOT NULL THEN
      SELECT conname INTO col FROM pg_constraint WHERE conrelid = tbl AND contype = 'p';
      EXECUTE format('ALTER TABLE public.payment_transactions DROP CONSTRAINT %I', col);
    END IF;
    ALTER TABLE public.payment_transactions ADD CONSTRAINT payment_transactions_pkey PRIMARY KEY (id);
  END IF;

  -- 7) Majburiy ustunlar: bo'sh qiymat bo'lmasa NOT NULL qo'yiladi.
  --    Eski yozuvlarda pack_id/coins kabi yangi ustunlar bo'sh bo'ladi — bu holda
  --    ustun ixtiyoriy qoladi (yangi yozuvlarni create-invoice baribir to'ldiradi).
  FOREACH col IN ARRAY ARRAY['user_id', 'provider', 'pack_id', 'amount_uzs', 'coins', 'status', 'created_at', 'updated_at'] LOOP
    EXECUTE format('SELECT EXISTS (SELECT 1 FROM public.payment_transactions WHERE %I IS NULL)', col) INTO has_nul;
    IF has_nul THEN
      RAISE NOTICE 'payment_transactions.%: eski yozuvlarda bo''sh — NOT NULL qo''yilmadi', col;
    ELSE
      EXECUTE format('ALTER TABLE public.payment_transactions ALTER COLUMN %I SET NOT NULL', col);
    END IF;
  END LOOP;

  -- 8) Tashqi kalitlar (ustunda hali yo'q bo'lsa)
  IF NOT EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
                  WHERE c.conrelid = tbl AND c.contype = 'f' AND a.attname = 'user_id') THEN
    ALTER TABLE public.payment_transactions ADD CONSTRAINT payment_transactions_user_id_fkey
      FOREIGN KEY (user_id) REFERENCES public.profiles(id) ON DELETE CASCADE NOT VALID;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
                  WHERE c.conrelid = tbl AND c.contype = 'f' AND a.attname = 'pack_id') THEN
    ALTER TABLE public.payment_transactions ADD CONSTRAINT payment_transactions_pack_id_fkey
      FOREIGN KEY (pack_id) REFERENCES public.coin_packs(id) NOT VALID;
  END IF;

  -- 9) Jadvalda eski trigger bo'lsa (tanga qo'shishi mumkin) — ogohlantiramiz
  FOR r IN SELECT tgname FROM pg_trigger WHERE tgrelid = tbl AND NOT tgisinternal LOOP
    RAISE NOTICE 'payment_transactions: eski trigger bor — %. Tanga ikki marta qo''shilmasligini tekshiring.', r.tgname;
  END LOOP;
END $mig$;

