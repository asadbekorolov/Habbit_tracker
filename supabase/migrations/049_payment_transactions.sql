-- ============================================================================
-- 049: To'lovlar poydevori (Click / Payme) — tanga paketlari
-- ============================================================================
-- Avval mijoz o'zi to'lov havolasini yasardi (narx va user_id URL'da, server
-- hech narsani tekshirmasdi, tanga hech qachon tushmasdi). Endi:
--   coin_packs            — narxlar faqat serverda (mijoz faqat pack_id yuboradi)
--   payment_transactions  — har bir buyurtma; Click/Payme callback'lari shu
--                           qatorni holatdan holatga o'tkazadi
--   credit_payment(id)    — to'lov tasdiqlanganda tanga qo'shadi (idempotent)
--   cancel_payment(id, r) — bekor qilish; to'langan bo'lsa tangani qaytarib oladi
-- Yozish faqat service_role orqali (api/payments/*). Foydalanuvchi faqat o'z
-- tranzaksiyalarini o'qiy oladi. Qayta ishga tushirish xavfsiz.
-- ============================================================================

BEGIN;

-- ── Paketlar katalogi ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.coin_packs (
  id          text PRIMARY KEY,
  coins       integer NOT NULL CHECK (coins > 0),
  bonus       integer NOT NULL DEFAULT 0 CHECK (bonus >= 0),
  price_uzs   integer NOT NULL CHECK (price_uzs > 0),   -- so'mda
  is_active   boolean NOT NULL DEFAULT true,
  sort_order  integer NOT NULL DEFAULT 0
);

INSERT INTO public.coin_packs (id, coins, bonus, price_uzs, sort_order) VALUES
  ('pack_small', 500,  0,   9900,  1),
  ('pack_gold',  1500, 150, 24900, 2),
  ('pack_chest', 5000, 550, 59900, 3)
ON CONFLICT (id) DO UPDATE SET
  coins = EXCLUDED.coins, bonus = EXCLUDED.bonus,
  price_uzs = EXCLUDED.price_uzs, sort_order = EXCLUDED.sort_order;

ALTER TABLE public.coin_packs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS coin_packs_read ON public.coin_packs;
CREATE POLICY coin_packs_read ON public.coin_packs FOR SELECT TO authenticated USING (is_active);
REVOKE ALL ON public.coin_packs FROM anon, authenticated;
GRANT SELECT ON public.coin_packs TO authenticated;

-- ── Tranzaksiyalar ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.payment_transactions (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Click merchant_prepare_id / merchant_confirm_id butun son bo'lishi kerak
  seq             bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  user_id         uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  provider        text NOT NULL CHECK (provider IN ('click', 'payme')),
  pack_id         text NOT NULL REFERENCES public.coin_packs(id),
  amount_uzs      integer NOT NULL CHECK (amount_uzs > 0),
  coins           integer NOT NULL CHECK (coins > 0),          -- coins + bonus (yaratilgan paytdagi)
  status          text NOT NULL DEFAULT 'created'
                  CHECK (status IN ('created', 'pending', 'paid', 'cancelled', 'failed')),
  provider_txn_id text,                                         -- click_trans_id / Payme transaction id
  provider_state  integer,                                      -- Payme: 1, 2, -1, -2
  provider_time   bigint,                                       -- Payme yaratish vaqti (ms)
  perform_time    timestamptz,
  cancel_time     timestamptz,
  cancel_reason   integer,
  last_payload    jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS payment_transactions_provider_txn_uidx
  ON public.payment_transactions (provider, provider_txn_id) WHERE provider_txn_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS payment_transactions_user_idx
  ON public.payment_transactions (user_id, created_at DESC);

ALTER TABLE public.payment_transactions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS payment_transactions_own_read ON public.payment_transactions;
CREATE POLICY payment_transactions_own_read ON public.payment_transactions
  FOR SELECT TO authenticated USING (user_id = auth.uid());
REVOKE ALL ON public.payment_transactions FROM anon, authenticated;
GRANT SELECT ON public.payment_transactions TO authenticated;

-- ── To'lovni tasdiqlash: tanga qo'shish (bir marta) ──────────────────────────
CREATE OR REPLACE FUNCTION public.credit_payment(p_txn_id uuid)
RETURNS TABLE (status text, coins_added integer, new_balance integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  t payment_transactions%ROWTYPE;
  v_balance integer;
BEGIN
  SELECT * INTO t FROM payment_transactions WHERE id = p_txn_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'transaction_not_found';
  END IF;
  IF t.status = 'paid' THEN
    -- Takroriy callback: hech narsa qo'shilmaydi
    RETURN QUERY SELECT 'already_paid'::text, 0, (SELECT p.coins FROM profiles p WHERE p.id = t.user_id);
    RETURN;
  END IF;
  IF t.status IN ('cancelled', 'failed') THEN
    RAISE EXCEPTION 'transaction_cancelled';
  END IF;

  PERFORM _lock_user_rewards(t.user_id);
  PERFORM _apply_balance(t.user_id, 0, t.coins, 0);
  UPDATE payment_transactions
     SET status = 'paid', perform_time = now(), updated_at = now()
   WHERE id = t.id;

  SELECT p.coins INTO v_balance FROM profiles p WHERE p.id = t.user_id;
  RETURN QUERY SELECT 'paid'::text, t.coins, v_balance;
END;
$$;

-- ── Bekor qilish (to'langan bo'lsa tanga qaytarib olinadi, manfiy bo'lishi mumkin) ──
CREATE OR REPLACE FUNCTION public.cancel_payment(p_txn_id uuid, p_reason integer DEFAULT NULL)
RETURNS TABLE (status text, coins_removed integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  t payment_transactions%ROWTYPE;
  v_removed integer := 0;
BEGIN
  SELECT * INTO t FROM payment_transactions WHERE id = p_txn_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'transaction_not_found';
  END IF;
  IF t.status = 'cancelled' THEN
    RETURN QUERY SELECT 'already_cancelled'::text, 0;
    RETURN;
  END IF;

  IF t.status = 'paid' THEN
    PERFORM _lock_user_rewards(t.user_id);
    PERFORM _apply_balance(t.user_id, 0, -t.coins, 0);
    v_removed := t.coins;
  END IF;

  UPDATE payment_transactions
     SET status = 'cancelled', cancel_time = now(), cancel_reason = p_reason, updated_at = now()
   WHERE id = t.id;

  RETURN QUERY SELECT 'cancelled'::text, v_removed;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.credit_payment(uuid)          FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.cancel_payment(uuid, integer) FROM PUBLIC, anon, authenticated;
GRANT  EXECUTE ON FUNCTION public.credit_payment(uuid)          TO service_role;
GRANT  EXECUTE ON FUNCTION public.cancel_payment(uuid, integer) TO service_role;

COMMIT;
