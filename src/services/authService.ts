import { Capacitor } from "@capacitor/core";
import { GoogleAuth } from "@codetrix-studio/capacitor-google-auth";
import { supabase } from "./supabase";
import type { Profile } from "./supabase";
import { getMyProfile } from "./db";

export interface GoogleSignInResult {
  data: any;
  profile: Profile | null;
  isNewUser?: boolean;
}

export const signInWithGoogle = async (): Promise<GoogleSignInResult> => {
  if (Capacitor.isNativePlatform()) {
    try {
      // Initialize native GoogleAuth
      await GoogleAuth.initialize({
        clientId: "512488053553-tjcrlmg447iupisp9ka3l9u67ip6rhmo.apps.googleusercontent.com",
        scopes: ["profile", "email"],
        grantOfflineAccess: true,
      });

      let googleUser: any;
      try {
        googleUser = await GoogleAuth.signIn();
      } catch (err: any) {
        const msg = err?.message || (typeof err === "object" ? JSON.stringify(err) : String(err));
        if (
          msg.includes("popup_closed") ||
          msg.includes("cancelled") ||
          msg.includes("canceled") ||
          err?.code === "12501" ||
          err?.code === 12501
        ) {
          throw new Error("USER_CANCELLED");
        }
        if (msg.includes("Something went wrong") || msg.includes("10:") || msg.includes("DEVELOPER_ERROR")) {
          throw new Error("Google OAuth SHA-1 kaliti Google Cloud Konsolida biriktirilishi va tasdiqlanishi kutilmoqda.");
        }
        throw new Error(`Google Native: ${msg}`);
      }

      const idToken = googleUser?.authentication?.idToken || (googleUser as any)?.idToken;
      if (!idToken) {
        throw new Error("Google idToken olinmadi");
      }

      const { data, error } = await supabase.auth.signInWithIdToken({
        provider: "google",
        token: idToken,
      });

      if (error) throw error;

      let profile: Profile | null = null;
      let isNewUser = false;

      if (data?.user) {
        const isCompleted = data.user.user_metadata?.registration_completed === true;

        // O'z profili (shaxsiy ustunlar bilan) — get_my_profile() RPC.
        const existingProfile = await getMyProfile().catch(() => null);

        if (existingProfile) {
          if (existingProfile.is_banned) {
            await supabase.auth.signOut();
            throw new Error("Sizning akkauntingiz ma'muriyat tomonidan bloklangan.");
          }

          const isAutoGeneratedUsername = /_\d{1,4}$/.test(existingProfile.username || "");

          if (!isCompleted && isAutoGeneratedUsername) {
            isNewUser = true;
            profile = null;
          } else {
            profile = existingProfile;
          }
        } else {
          isNewUser = true;
          profile = null;
        }
      }

      return { data, profile, isNewUser };
    } catch (err: any) {
      throw err;
    }
  } else {
    // Standard Web Flow
    const { data, error } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: {
        redirectTo: `${window.location.origin}/auth/callback`,
      },
    });

    if (error) throw error;
    return { data, profile: null };
  }
};
