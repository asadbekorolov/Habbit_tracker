import React, { createContext, useContext, useState, useEffect, useCallback, useRef } from 'react';
import { supabase } from '../services/supabase';
import type { Profile } from '../services/supabase';
import { getMyProfile } from '../services/db';
import { habitSyncQueue, migrateLegacyPendingLogs } from '../services/habitSyncQueue';
import { clearQueryCache } from '../services/queryClient';

interface UserContextType {
  profile: Profile | null;
  setProfile: React.Dispatch<React.SetStateAction<Profile | null>>;
  refreshUserProfile: () => Promise<void>;
  updateCoins: (newCoins: number) => void;
  loading: boolean;
}

const UserContext = createContext<UserContextType | undefined>(undefined);

export function UserProvider({ children }: { children: React.ReactNode }) {
  const [profile, setProfile] = useState<Profile | null>(() => {
    try {
      const cached = localStorage.getItem('user_profile_latest');
      return cached ? JSON.parse(cached) : null;
    } catch {
      return null;
    }
  });
  const [loading, setLoading] = useState<boolean>(() => !profile);

  const refreshUserProfile = useCallback(async () => {
    const { data: { session } } = await supabase.auth.getSession();
    const user = session?.user;
    const userId = user?.id;
    if (!userId) {
      setProfile(null);
      setLoading(false);
      return;
    }

    // O'z profili (shaxsiy ustunlar bilan) — get_my_profile() RPC.
    let data: Profile | null = null;
    let error: unknown = null;
    try {
      data = await getMyProfile();
    } catch (e) {
      error = e;
    }

    if (data && !error) {
      const isCompleted = user.user_metadata?.registration_completed === true;
      const isAutoGeneratedUsername = /_\d{1,4}$/.test(data.username || "");

      // Allow login only if explicitly completed OR if it's an existing registered user
      if (isCompleted) {
        setProfile(data);
        localStorage.setItem(`user_profile_${userId}`, JSON.stringify(data));
        localStorage.setItem('user_profile_latest', JSON.stringify(data));
      } else if (!isAutoGeneratedUsername && user.user_metadata?.registration_completed === undefined) {
        // Legacy user with custom username
        setProfile(data);
        localStorage.setItem(`user_profile_${userId}`, JSON.stringify(data));
        localStorage.setItem('user_profile_latest', JSON.stringify(data));
      } else {
        // Incomplete / New Google user -> Stay on Login/Register completion screen
        setProfile(null);
        localStorage.removeItem('user_profile_latest');
      }
    } else {
      setProfile(null);
      localStorage.removeItem('user_profile_latest');
    }
    setLoading(false);
  }, []);

  const updateCoins = useCallback((newCoins: number) => {
    setProfile(prev => {
      if (!prev) return null;
      const updated = { ...prev, coins: newCoins };
      localStorage.setItem(`user_profile_${prev.id}`, JSON.stringify(updated));
      localStorage.setItem('user_profile_latest', JSON.stringify(updated));
      return updated;
    });
  }, []);

  // Sinxronizatsiya navbati: foydalanuvchi aniqlanishi bilan saqlangan
  // belgilar darhol yuboriladi; chiqishda to'xtatiladi.
  // Boshqa akkauntga o'tilsa — oldingi foydalanuvchining keshi tozalanadi.
  // (Profil vaqtincha null bo'lishi — masalan oflaynda — keshni o'chirmaydi;
  // aniq chiqish App.handleLogout'da tozalanadi.)
  const prevUserIdRef = useRef<string | null>(null);
  useEffect(() => {
    const prev = prevUserIdRef.current;
    if (prev && profile?.id && prev !== profile.id) void clearQueryCache();
    if (profile?.id) prevUserIdRef.current = profile.id;
    if (profile?.id) {
      habitSyncQueue.start(profile.id);
      migrateLegacyPendingLogs(profile.id);
    } else {
      habitSyncQueue.stop();
    }
  }, [profile?.id]);

  // Server javobidagi yangi balans/daraja darhol profilga yoziladi.
  useEffect(() => {
    const onSynced = (e: Event) => {
      const r = (e as CustomEvent).detail?.result;
      if (!r || typeof r.coins !== 'number') return;
      setProfile(prev => {
        if (!prev) return prev;
        const updated = {
          ...prev,
          coins: r.coins,
          score: r.score ?? prev.score,
          total_xp: r.total_xp ?? prev.total_xp,
          current_level: r.level ?? prev.current_level,
        };
        try {
          localStorage.setItem(`user_profile_${prev.id}`, JSON.stringify(updated));
          localStorage.setItem('user_profile_latest', JSON.stringify(updated));
        } catch { /* storage to'la */ }
        return updated;
      });
    };
    window.addEventListener('habit-sync-success', onSynced);
    return () => window.removeEventListener('habit-sync-success', onSynced);
  }, []);

  useEffect(() => {
    refreshUserProfile();

    const { data: { subscription } } = supabase.auth.onAuthStateChange((_event, session) => {
      if (session?.user) {
        refreshUserProfile();
      } else {
        setProfile(null);
        localStorage.removeItem('user_profile_latest');
        setLoading(false);
      }
    });

    return () => subscription.unsubscribe();
  }, [refreshUserProfile]);

  return (
    <UserContext.Provider value={{ profile, setProfile, refreshUserProfile, updateCoins, loading }}>
      {children}
    </UserContext.Provider>
  );
}

export function useUser() {
  const context = useContext(UserContext);
  if (context === undefined) {
    throw new Error('useUser must be used within a UserProvider');
  }
  return context;
}

/**
 * Himoyalangan sahifalar uchun: joriy profil (doim mavjud).
 * App.renderLayout profil bo'lmasa sahifani chizmaydi (login'ga yo'naltiradi),
 * shuning uchun bu hook faqat profil yuklangandan keyin chaqiriladi.
 */
export function useProfile(): Profile {
  const { profile } = useUser();
  if (!profile) {
    throw new Error("useProfile: profil hali yuklanmagan (himoyalangan sahifadan tashqarida chaqirildi)");
  }
  return profile;
}
